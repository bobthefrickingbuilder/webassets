// Scans effects/**/*.html and writes effects/manifest.js for the gallery.
// Each effect page declares its metadata in <title> and <meta> tags, so this is the only index to maintain.
// Usage: node scripts/build-manifest.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(import.meta.url), "..", "..");
const effectsDir = join(root, "effects");

export const CATEGORIES = {
  "01-scroll": "Scroll",
  "02-text": "Text & Typography",
  "03-cursor": "Cursor & Pointer",
  "04-micro": "Buttons & Micro-interactions",
  "05-backgrounds": "Backgrounds & Heroes",
  "06-galleries": "Cards, Images & Galleries",
  "07-navigation": "Transitions & Navigation",
  "08-loaders": "Loaders & Progress",
  "09-svg-css": "SVG, CSS & Filters",
  "10-webgl": "WebGL / WebGPU / 3D",
  "11-physics": "Physics & Play",
  "12-experimental": "Exotic & Experimental",
  "13-components": "Animated UI Components",
};

const meta = (html, name) => {
  const m = html.match(new RegExp(`<meta\\s+name="${name}"\\s+content="([^"]*)"`, "i"));
  return m ? m[1] : "";
};

const effects = [];
for (const cat of readdirSync(effectsDir).sort()) {
  const dir = join(effectsDir, cat);
  if (!statSync(dir).isDirectory() || !CATEGORIES[cat]) continue;
  for (const file of readdirSync(dir).sort()) {
    if (!file.endsWith(".html")) continue;
    const html = readFileSync(join(dir, file), "utf8");
    const num = parseInt(file, 10);
    effects.push({
      num,
      title: (html.match(/<title>([^<]*)<\/title>/i) || [, file])[1].trim(),
      description: meta(html, "description"),
      tech: meta(html, "tech").split(",").map((s) => s.trim()).filter(Boolean),
      complexity: parseInt(meta(html, "complexity"), 10) || 1,
      category: cat,
      path: relative(root, join(dir, file)).split("\\").join("/"),
    });
  }
}
effects.sort((a, b) => a.num - b.num);

const out =
  "// Generated by scripts/build-manifest.mjs. Do not edit by hand.\n" +
  "window.EFFECT_CATEGORIES = " + JSON.stringify(CATEGORIES, null, 2) + ";\n" +
  "window.EFFECTS = " + JSON.stringify(effects, null, 1) + ";\n";
writeFileSync(join(effectsDir, "manifest.js"), out);
console.log(`Wrote ${effects.length} effects to effects/manifest.js`);
